# Variáveis e tipos de dados "básicos"

# Uma variável é um espaço na memória onde armazenamos um valor.

nome = "Isabela"  # variável do tipo string (texto)
idade = 30       # variável do tipo inteiro (número sem casa decimal)
altura = 1.62    # variável do tipo float (número com casa decimal)
estudando = True  # variável do tipo booleano (True ou False)

print(f"Olá, meu nome é {nome}, tenho {idade} anos, minha altura é {altura}m.")